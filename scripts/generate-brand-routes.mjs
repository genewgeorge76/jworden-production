#!/usr/bin/env node
/**
 * generate-brand-routes.mjs — the exact path list for each brand-directory host.
 *
 * WHY THIS EXISTS
 * ───────────────
 * Brand-directory hosts (texaspavementgroup.com) are served out of
 * /brands/<host>/ by a host rewrite in vercel.json. That rewrite is not enough
 * on its own, for two reasons found live:
 *
 *   1. Vercel checks the FILESYSTEM before applying vercel.json rewrites. The
 *      SPA prerenders /residential, /services, /service-areas and /contact into
 *      the deploy root, so those four paths were served as VIRGINIA pages on the
 *      Texas domain. /commercial happened to work only because no file of that
 *      name exists at the root.
 *
 *   2. A path with no brand file fell through to the SPA catch-all and returned
 *      200 with the software storefront — a soft 404, which is the exact thing
 *      middleware.js exists to prevent everywhere else.
 *
 * With this manifest middleware can rewrite EXPLICITLY to the brand file, which
 * beats the filesystem, and return a real 404 for anything not in the list.
 *
 * Generated in prebuild and committed, for the same reason
 * route-manifest.generated.js is: middleware is bundled from source at build
 * time and cannot read something postbuild writes.
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Must stay in step with ROUTES in scripts/build-brand-sites.mjs.
const BRAND_ROUTES = ['/', '/commercial', '/residential', '/services', '/service-areas', '/contact'];

const { texasCityPages } = await import(
  pathToFileURL(resolve(ROOT, 'src/data/texasCityPages.js')).href
);

const BRANDS = {
  'texaspavementgroup.com': [...BRAND_ROUTES, ...texasCityPages().map((c) => c.path)],
};

const body = `// GENERATED by scripts/generate-brand-routes.mjs — do not edit by hand.
// Regenerated on every build (prebuild); committed so middleware can resolve it.
export default ${JSON.stringify(BRANDS, null, 2)};
`;

writeFileSync(resolve(ROOT, 'brand-routes.generated.js'), body, 'utf8');
for (const [host, paths] of Object.entries(BRANDS)) {
  console.log(`[brand-routes] ${host}: ${paths.length} paths`);
}
