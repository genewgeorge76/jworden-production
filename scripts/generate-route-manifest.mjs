/**
 * Generates route-manifest.generated.js from the router in src/App.jsx.
 *
 * WHY THIS IS GENERATED AND NOT HAND-WRITTEN
 *
 * middleware.js uses this list to decide which paths are real, so that unknown
 * URLs can return a true 404 instead of 200-with-the-homepage (a "soft 404").
 * A hand-maintained copy would drift the first time someone adds a route to
 * App.jsx, and the failure mode of drift here is the worst one available: a
 * live money page starts returning 404 to Google. Deriving it from the router
 * means the list cannot disagree with the app.
 *
 * Two kinds of entry come out of this:
 *
 *   exact    "/services", "/crack-repair"      — matched literally
 *   prefixes "/blog/", "/states/"              — from ":param" routes, where
 *                                                any child segment may be real
 *
 * Dynamic routes are deliberately treated as "anything under here is real".
 * /states/:stateSlug means /states/<garbage> still returns 200 — this pass does
 * not fix that, and pretending otherwise would risk 404ing a legitimate city or
 * state page. What it does fix is the large class of wholly unknown paths,
 * which is where the soft-404 exposure actually comes from.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const APP = path.join(ROOT, 'src', 'App.jsx')
const OUT = path.join(ROOT, 'route-manifest.generated.js')

const src = fs.readFileSync(APP, 'utf-8')
const declared = [...src.matchAll(/path="([^"]+)"/g)].map(m => m[1])

// Not every route is a literal path="..." in App.jsx. publicAIPages and
// internalAIPages are registered programmatically:
//
//     {[...filteredPublicAIPages].map(({ path, Component }) => (
//       <Route key={path} path={path} element={<Component />} />
//     ))}
//
// so a regex over App.jsx alone misses all of them — /background-checks,
// /employee-handbook, /payroll-compliance and the rest. They are absent from
// the sitemaps too, which means the sitemap-coverage guard cannot see them
// either. Left out, middleware would have returned 404 for every one of these
// live pages. Any future registry of the same shape must be added here.
const REGISTRY = path.join(ROOT, 'src', 'generated', 'aiPageRegistry.jsx')
if (fs.existsSync(REGISTRY)) {
  const reg = fs.readFileSync(REGISTRY, 'utf-8')
  for (const m of reg.matchAll(/path:\s*['"]([^'"]+)['"]/g)) declared.push(m[1])
}

const exact = new Set()
const prefixes = new Set()

for (const raw of declared) {
  if (!raw || raw === '*' || raw === '/*') continue          // the app's own catch-all
  const p = raw.startsWith('/') ? raw : `/${raw}`
  const idx = p.indexOf('/:')
  if (idx === -1 && !p.includes('*')) {
    exact.add(p)
  } else {
    // "/locations/richmond-va/:zip" -> "/locations/richmond-va/"
    const base = idx === -1 ? p.replace(/\*.*$/, '') : p.slice(0, idx + 1)
    if (base && base !== '/') prefixes.add(base)
  }
}

// Routes the prerenderer deliberately skips (private app surfaces). They are
// real and must keep serving the SPA even though they will never be a file in
// the build output. Keep in sync with SKIP_ROUTES in scripts/prerender.mjs.
for (const p of [
  '/command-center', '/dashboard', '/leads', '/portal', '/staff',
  '/voice-calls', '/revenue', '/candidate', '/dns-migration', '/admin',
]) exact.add(p)

const manifest = {
  generatedAt: new Date().toISOString(),
  exact: [...exact].sort(),
  prefixes: [...prefixes].sort(),
}

// Emitted as a JS module rather than JSON: middleware runs on Vercel's edge
// runtime, where JSON import attributes are not dependable. A plain ESM export
// bundles the same way everywhere.
fs.writeFileSync(
  OUT,
  '// GENERATED by scripts/generate-route-manifest.mjs — do not edit by hand.\n'
  + '// Regenerated on every build (prebuild); committed so middleware always resolves it.\n'
  + `export default ${JSON.stringify(manifest, null, 2)}\n`,
  'utf-8',
)
console.log(`[route-manifest] ${manifest.exact.length} exact + ${manifest.prefixes.length} prefixes`)
