#!/usr/bin/env node
/**
 * build-georgia-city-counties.mjs — which county each Georgia city page is in.
 *
 * WHY THIS EXISTS
 * ───────────────
 * The city pages group cities into sectors, and each sector names the counties
 * it covers. Those groupings were written by hand, and one was wrong: Clarkston
 * was filed under "South Metro Atlanta — Clayton, south Fulton and Fayette",
 * carrying a paragraph about the Hartsfield freight economy.
 *
 * Clarkston is in DeKalb County, inside I-285 on the northeast side, twenty-five
 * miles from the airport. The name looks like Clayton. That is the whole
 * explanation, and it is the kind of error that is invisible to whoever wrote it
 * and obvious to a reader in Clarkston — who is the reader the page is for.
 *
 * TWO WRONG APPROACHES, RECORDED SO THEY ARE NOT REPEATED
 * ──────────────────────────────────────────────────────
 * First attempt geocoded each city name and, to "sharpen" the match, passed the
 * county from the page's own sector as a hint: "Cartersville, Cobb County,
 * Georgia". Every answer came back agreeing with the page. Cartersville is in
 * Bartow. Chamblee and Tucker came back Gwinnett; both are DeKalb. A check fed
 * the thing it is checking is not a check.
 *
 * Second attempt dropped the hint but tried to catch bad name matches by testing
 * them against the counties where invoiced stores are. That rejected Covington —
 * correctly Newton — because no KBP store happens to be in Newton, and it matched
 * "Union City" against a store in Union City, New Jersey.
 *
 * WHAT ACTUALLY ANSWERS IT
 * ────────────────────────
 * The Census Bureau's place file states the county for every incorporated place
 * outright. No geocoder, no name matching, no threshold to tune — the federal
 * register simply says which county a city is in, and says when a city spans
 * two.
 *
 * It also separates the two kinds of page name cleanly. Thirteen of these pages
 * are named for incorporated cities and appear in the file. Four are named for
 * road corridors and neighbourhoods the punch list used — Adamsville, Holcomb
 * Bridge, Pleasant Hill, Sugarloaf — and do not appear, because they are not
 * places in the federal sense. Those are recorded unresolved rather than guessed:
 * "Pleasant Hill, Georgia" in a gazetteer is a community in Union County, ninety
 * miles from the I-85 retail intersection the page is about.
 *
 * Usage:  node scripts/build-georgia-city-counties.mjs [outFile]
 */

import { writeFileSync } from 'node:fs'

import { georgiaCityPages } from '../src/data/georgiaCityPages.js'

const UA = 'JWordenSonsPaving-CountyFacts/1.0 (https://jwordenasphaltpaving.com)'
const PLACES_URL = 'https://www2.census.gov/geo/docs/reference/codes2020/national_place2020.txt'
const OUT = process.argv[2] ?? 'src/data/georgiaCityCounties.json'

const res = await fetch(PLACES_URL, { headers: { 'User-Agent': UA } })
if (!res.ok) {
  console.error(`${res.status} from the Census place file. Nothing written.`)
  process.exit(1)
}

const [header, ...lines] = (await res.text()).trim().split(/\r?\n/)
const keys = header.split('|')
const georgia = lines
  .map((l) => Object.fromEntries(l.split('|').map((v, i) => [keys[i], v])))
  .filter((r) => r.STATE === 'GA')

/**
 * The file names a place "Acworth city" or "Tucker city". Only incorporated
 * places are matched: a census-designated place is a statistical shape drawn
 * around a settlement, not a municipality, and matching those would resolve
 * corridor names to whatever shape happens to carry the label.
 */
function placeFor(city) {
  return georgia.find(
    (r) =>
      r.TYPE === 'INCORPORATED PLACE' &&
      r.PLACENAME.replace(/ (city|town|village)$/, '') === city,
  )
}

const cities = georgiaCityPages().map((page) => {
  const place = placeFor(page.city)
  // A place spanning two counties is listed with both, separated by ~~~. Both
  // are kept: Villa Rica genuinely straddles the Carroll–Douglas line, and
  // picking one would make the page wrong for half the town.
  const counties = place
    ? place.COUNTIES.split('~~~').map((c) => c.replace(/ County$/, '').trim())
    : null
  return {
    city: page.city,
    path: page.path,
    sector: page.sector,
    sector_counties: page.counties,
    counties,
    place_name: place?.PLACENAME ?? null,
    place_fips: place ? `13${place.PLACEFP}` : null,
    // Stated rather than inferred, so a null is never read as an oversight.
    unresolved_reason: place
      ? null
      : 'not an incorporated place in the Census register — the page is named for a road corridor or neighbourhood, which a place lookup cannot resolve',
  }
})

writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        'Generated by scripts/build-georgia-city-counties.mjs from the US Census Bureau place file. The county each Georgia city page is in, stated by the federal register rather than assigned by hand. Do not hand-edit.',
      _source: PLACES_URL,
      _generated_utc: new Date().toISOString(),
      cities_total: cities.length,
      cities_resolved: cities.filter((c) => c.counties).length,
      cities,
    },
    null,
    2,
  ) + '\n',
  'utf8',
)

for (const c of cities) {
  console.log(`  ${c.city.padEnd(16)} -> ${c.counties?.join(' / ') ?? 'not an incorporated place'}`)
}
console.log(`\n${cities.filter((c) => c.counties).length}/${cities.length} resolved → ${OUT}`)
