#!/usr/bin/env node
/**
 * build-gdot-counties.mjs — Georgia's counties as the state DOT files them.
 *
 * WHY NOT REUSE THE VIRGINIA SHAPE
 * ────────────────────────────────
 * The Virginia county pages carry VDOT's district and VDOT mix codes, because
 * in Virginia those are the facts. None of them are true in Georgia. VDOT
 * SM-9.5A is not a thing GDOT specifies, and "VDOT's Staunton District" names
 * no part of Georgia. Copying the Virginia page across the state line would
 * put confident, checkable, wrong statements in front of the exact readers who
 * would know — which is worse than saying nothing.
 *
 * So Georgia gets Georgia's facts, from Georgia's DOT.
 *
 * SOURCE
 * ──────
 * GDOT publishes its own county boundary layer with the district each county
 * belongs to, its Metropolitan Planning Organization and its Regional
 * Commission. That is the authority on which district a county is in — not a
 * map redrawn by hand, and not a recollection of one.
 *
 *   https://rnhp.dot.ga.gov/hosting/rest/services/GDOT_Boundaries/MapServer/1
 *
 * No key. Nothing here is authored: if the service does not return a field for
 * a county, the field is null.
 *
 * Usage:  node scripts/build-gdot-counties.mjs [outFile]
 */

import { writeFileSync } from 'node:fs'

const UA = 'JWordenSonsPaving-CountyFacts/1.0 (https://jwordenasphaltpaving.com)'
const LAYER =
  'https://rnhp.dot.ga.gov/hosting/rest/services/GDOT_Boundaries/MapServer/1'
const OUT = process.argv[2] ?? 'src/data/gdotCounties.json'

const url =
  `${LAYER}/query?` +
  new URLSearchParams({
    where: '1=1',
    outFields: 'NAME,COUNTYFP,GDOT_DISTRICT,MPO,REGIONAL_COMMISSION,TMA',
    returnGeometry: 'false',
    f: 'json',
  })

const res = await fetch(url, { headers: { 'User-Agent': UA } })
if (!res.ok) {
  console.error(`${res.status} from GDOT. Nothing written.`)
  process.exit(1)
}
const body = await res.json()
const features = body?.features ?? []
if (features.length !== 159) {
  // Georgia has 159 counties. A short answer means the query was truncated or
  // the layer changed shape, and a partial county table is worse than none:
  // a county missing from it silently loses its district on the page.
  console.error(`GDOT returned ${features.length} counties, expected 159. Nothing written.`)
  process.exit(1)
}

/** Empty strings and the literal "None" the service uses both mean "no value". */
const orNull = (v) => {
  const s = String(v ?? '').trim()
  return s && s !== 'None' ? s : null
}

const counties = features
  .map((f) => f.attributes)
  .map((a) => ({
    county: a.NAME,
    fips: a.COUNTYFP ? `13${a.COUNTYFP}` : null,
    gdot_district: orNull(a.GDOT_DISTRICT),
    // A county can sit in more than one MPO; the service comma-separates them.
    mpo: orNull(a.MPO)?.split(',').map((s) => s.trim()) ?? null,
    regional_commission: orNull(a.REGIONAL_COMMISSION),
    tma: orNull(a.TMA),
  }))
  .sort((a, b) => a.county.localeCompare(b.county))

writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        'Generated by scripts/build-gdot-counties.mjs from the Georgia Department of Transportation boundary service. Every field is fetched, never authored. Do not hand-edit.',
      _source: `${LAYER} — GDOT_Boundaries, Counties layer`,
      _generated_utc: new Date().toISOString(),
      counties_total: counties.length,
      districts: [...new Set(counties.map((c) => c.gdot_district).filter(Boolean))].sort(),
      counties,
    },
    null,
    2,
  ) + '\n',
  'utf8',
)

console.log(`${counties.length} Georgia counties → ${OUT}`)
const byDistrict = {}
for (const c of counties) (byDistrict[c.gdot_district] ??= []).push(c.county)
for (const [d, list] of Object.entries(byDistrict).sort()) {
  console.log(`  District ${d}: ${list.length} counties`)
}
