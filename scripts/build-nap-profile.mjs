/**
 * build-nap-profile.mjs — generate the NAP profile from the one canonical source.
 *
 * WHY THIS SCRIPT EXISTS RATHER THAN A HAND-MAINTAINED FILE
 * ────────────────────────────────────────────────────────
 * src/data/napProfile.json used to be hand-written, and it had drifted into
 * fiction. Every field in it was wrong:
 *
 *   street    "123 Paving Way"        — not an address. A placeholder.
 *   phone     "+1-804-555-0199"       — the 555 range is reserved for fiction.
 *   founded   "since 1999"            — the company was founded in 1984.
 *   postcode  "23831"                 — Chester VA, but the wrong one; 23836.
 *   Saturday  "08:00-14:00"           — opens at 07:00.
 *
 * None of that was malicious. It is what happens to a SECOND source of truth:
 * businessInfo.canonical.js was kept current (the address carries a "verified
 * 2026-05-10" note) and this file was not, because nothing forced them to
 * agree. So the fix is not to correct the numbers — it is to stop there being
 * two places to correct.
 *
 * WHY A WRONG NAP IS WORSE THAN NO NAP
 * ────────────────────────────────────
 * NAP is Name, Address, Phone, and its entire value to a local search ranking
 * is CONSISTENCY. Google builds confidence in a business entity by seeing the
 * same three facts agree across the site, the Business Profile, and every
 * directory that lists it. A citation that disagrees does not count for
 * nothing — it counts against, because it is evidence the engine cannot
 * resolve which business this is.
 *
 * A site publishing "123 Paving Way / 804-555-0199" was therefore not merely
 * failing to help. It was actively supplying a conflicting citation about its
 * own company, in schema.org markup, from the most authoritative source Google
 * has for it.
 *
 * Run: node scripts/build-nap-profile.mjs
 */

import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  ADDRESS,
  BUSINESS_DESCRIPTION,
  BUSINESS_FOUNDING_YEAR,
  BUSINESS_NAME,
  EMAIL,
  GEO,
  OPENING_HOURS,
  PHONE_SCHEMA,
  SITE_URL,
} from '../src/lib/businessInfo.canonical.js'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const TARGET = resolve(ROOT, 'src/data/napProfile.json')

const DAYS = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']

/** OPENING_HOURS groups days; directories want one line per day. */
function hoursByDay() {
  const hours = Object.fromEntries(DAYS.map((d) => [d, 'Closed']))
  for (const block of OPENING_HOURS) {
    for (const day of block.dayOfWeek) hours[day] = `${block.opens}-${block.closes}`
  }
  return hours
}

const profile = {
  _generated:
    'Generated by scripts/build-nap-profile.mjs from src/lib/businessInfo.canonical.js. ' +
    'Do not hand-edit — a second source of truth is how this file became fiction.',
  businessName: BUSINESS_NAME,
  address: {
    street: ADDRESS.streetAddress,
    city: ADDRESS.addressLocality,
    state: ADDRESS.addressRegion,
    zipCode: ADDRESS.postalCode,
    country: ADDRESS.addressCountry,
  },
  geo: { latitude: GEO.latitude, longitude: GEO.longitude },
  phone: PHONE_SCHEMA,
  email: EMAIL,
  website: SITE_URL,
  foundingYear: BUSINESS_FOUNDING_YEAR,
  description: BUSINESS_DESCRIPTION,
  categories: ['Paving Contractor', 'Asphalt Contractor', 'Concrete Contractor'],
  hours: hoursByDay(),
}

writeFileSync(TARGET, `${JSON.stringify(profile, null, 2)}\n`, 'utf8')
console.log(`wrote ${TARGET.replace(`${ROOT}/`, '')}`)
console.log(`  ${profile.businessName}`)
console.log(`  ${profile.address.street}, ${profile.address.city}, ${profile.address.state} ${profile.address.zipCode}`)
console.log(`  ${profile.phone}`)
